"""Run the fixed 73-subject reference experiment and recover CPU-allocation exits.

No cloud resources, no scheduled job, no changes to system settings. All results
are generated by run_reproduction.py. A retry resumes the latest valid
checkpoint; it never changes a hyperparameter or repairs a model silently.
"""
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "runs" / "dmer_code_73"
LOGS = ROOT / "runs" / "dmer_worker"


def save_json(path, value):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, path)


def main():
    LOGS.mkdir(parents=True, exist_ok=True)
    if (LOGS / "status.json").exists():
        raise RuntimeError("Worker status already exists; inspect the existing process before relaunching")
    for attempt in range(1, 21):
        command = [sys.executable, "-u", str(ROOT / "run_reproduction.py"),
                   "--implementation", "code-repaired", "--output", str(OUTPUT)]
        if (OUTPUT / "manifest.json").exists():
            command.append("--resume")
        out_path, err_path = LOGS / ("attempt_%02d.stdout.log" % attempt), LOGS / ("attempt_%02d.stderr.log" % attempt)
        with out_path.open("x", encoding="utf-8") as stdout, err_path.open("x", encoding="utf-8") as stderr:
            child = subprocess.Popen(command, cwd=ROOT, stdout=stdout, stderr=stderr)
            save_json(LOGS / "status.json", {"state": "running", "attempt": attempt, "pid": child.pid,
                                              "command": command, "started_local": time.strftime("%Y-%m-%d %H:%M:%S")})
            code = child.wait()
        if code == 0:
            save_json(LOGS / "status.json", {"state": "complete", "attempts": attempt,
                                              "finished_local": time.strftime("%Y-%m-%d %H:%M:%S"), "results": str(OUTPUT)})
            return
        error = err_path.read_text(encoding="utf-8", errors="replace")
        if "DefaultCPUAllocator: not enough memory" not in error:
            save_json(LOGS / "status.json", {"state": "failed", "attempts": attempt, "exit_code": code, "error_log": str(err_path)})
            raise RuntimeError("Experiment failed; inspect " + str(err_path))
        # This precise failure was observed at checkpoint saves. Retry from the
        # last atomic checkpoint after the old process has released its memory.
        save_json(LOGS / "status.json", {"state": "restarting_after_cpu_allocation_failure", "attempts": attempt,
                                          "error_log": str(err_path)})
        time.sleep(2)
    save_json(LOGS / "status.json", {"state": "failed", "attempts": 20, "reason": "CPU allocation retry limit reached"})
    raise RuntimeError("CPU allocation retry limit reached")


if __name__ == "__main__":
    main()
